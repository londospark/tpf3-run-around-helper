-- Load-time script (mod.json postRunScript). Prepares every rail vehicle (locos,
-- coaches and wagons) the game knows about, INCLUDING modded ones, so that the run-around ghost can be drawn
-- from the loco's OWN model with its own sound, smoke, wheels and paint.
--
-- A free entity has no vehicle data, and the game's sound and transformator scripts
-- for locos read vehicle data (the stock sound script dies with "attempt to index
-- local 'vehicleInfo'"). So for each loco:
--
--  * its transformator, when it is the stock train one (default_train.trf), is
--    pointed at res/models/runaround_ghost/real.trf, whose script
--    (res/scripts/ghost_real.script.lua) does exactly what the stock one does for a
--    real train and drives wheels, smoke and paint from the ghost's state for a
--    free entity;
--  * its sound set, when it is one of the game's own, is pointed at the matching
--    copy in res/audio/ghostwrap/: the same sound set with its update script
--    wrapped the same way. (The game refuses sound sets added or changed at run
--    time - soundSetRep.addAsTable / setAsTable throw std::exception - so these
--    copies are shipped as files, generated from the game's own.)
--
-- A loco for which both went through is marked with a marker model,
-- "runaround_ghost_real/<file>.mdl", which the run-around script looks for (a game
-- script cannot read model metadata). For every loco a ghost COPY is also built,
-- "runaround_ghost_dyn/<file>.mdl" (its meshes, particles, the wrapped sound set if
-- there is one, and the wrapped transformator), used when the loco's own model
-- cannot be: e.g. a modded loco with its own sound set or transformator script.
--
-- Markers and copies are named by the model's FILE name, because that is what is
-- known to match between here and the game script (the run-around looks them up
-- by the file name of a train's loco, which works live; whether full model names
-- read the same in both places has not been shown). So a file name that two or
-- more rail vehicles share (two mods' "loco.mdl", say) would be ambiguous: those
-- vehicles are left exactly as they are, with no marker and no copy, and the
-- run-around gives them the generic ghost (and coaches stay in view).
--
-- Everything is wrapped in pcall: a loco the game will not let us change is left
-- exactly as it was.

